// R307 (Lucas R300-05): an HTML error page with a 5xx status (CloudFront's 502, 503 and 504 pages) is not an
// expired session. Before this, any text/html answer counted as one, so the client signed in again and sent the
// same request a second time: a POST that had already done its work behind a 504 could run twice. Now a 5xx is
// handed back as it came, with one request and no sign-in. An HTML page below 500 (the login page) still counts.
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import http from "node:http";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

let server, home, base, routes, seen, apiClient, verdict;

const PAGE = "<!DOCTYPE HTML><html><head><title>ERROR: The request could not be satisfied</title></head><body><h1>504 Gateway Timeout ERROR</h1><p>Generated by cloudfront (CloudFront)</p></body></html>";
const HTML = { "content-type": "text/html; charset=utf-8" };

before(async () => {
  server = http.createServer((req, res) => {
    let body = "";
    req.on("data", (c) => (body += c));
    req.on("end", () => {
      const path = req.url.replace(/^\/api/, "");
      seen.push({ method: req.method, path });
      const json = (status, data, headers = {}) => {
        res.writeHead(status, { "content-type": "application/json", ...headers });
        res.end(JSON.stringify(data));
      };
      if (path === "/auth/csrf") return json(200, { csrfToken: "csrf-test" }, { "set-cookie": "authjs.csrf-token=csrf-test; Path=/" });
      if (path === "/auth/callback/credentials") return json(200, { url: "/" }, { "set-cookie": "authjs.session-token=renewed; Path=/; HttpOnly" });
      const route = routes[`${req.method} ${path}`];
      const [status, text, headers] = (typeof route === "function" ? route() : route) ?? [404, '{"error":"not here"}', {}];
      res.writeHead(status, { "content-type": "application/json", ...headers });
      res.end(text);
    });
  });
  await new Promise((r) => server.listen(0, "127.0.0.1", r));
  base = `http://127.0.0.1:${server.address().port}`;
  home = mkdtempSync(join(tmpdir(), "uiiq-mcp-test-home-"));
  mkdirSync(join(home, ".uiiq"));
  writeCreds();
  process.env.HOME = home;
  process.env.USERPROFILE = home;
  process.env.UIIQ_BASE = base;
  delete process.env.UIIQ_MCP_INHERIT_IMPERSONATION;
  ({ apiClient, verdict } = await import("../src/auth.js"));
});
after(async () => {
  server.closeAllConnections();
  await new Promise((r) => server.close(r));
  rmSync(home, { recursive: true, force: true });
});

// A stored login (email and password), so an expired session can sign in again by itself.
function writeCreds() {
  writeFileSync(join(home, ".uiiq", "credentials.json"), JSON.stringify({ base, sessionToken: "old", cookieName: "authjs.session-token", email: "office@workspace.test", password: "pw-test" }));
}
function prepare(r) {
  writeCreds();
  routes = r;
  seen = [];
}
const seq = (...answers) => () => (answers.length > 1 ? answers.shift() : answers[0]);
const signIns = () => seen.filter((q) => q.path === "/auth/callback/credentials");
const posts = () => seen.filter((q) => q.method === "POST" && q.path === "/charged/thing");

for (const status of [502, 503, 504]) {
  test(`an HTML ${status} is handed back as it came: one request, no sign-in, no second send`, async () => {
    prepare({ "POST /charged/thing": seq([status, PAGE, HTML], [200, '{"made":"twice"}', {}]) });
    const res = await apiClient()("/charged/thing", { method: "POST", body: JSON.stringify({ requestId: "r-1" }) });
    assert.equal(res.status, status);
    assert.match(await res.text(), /Gateway Timeout|could not be satisfied/);
    assert.equal(posts().length, 1);
    assert.equal(signIns().length, 0);
  });
}

test("a JSON 500 was never an expired session, and still isn't", async () => {
  prepare({ "POST /charged/thing": seq([500, '{"error":"Server error"}', {}], [200, '{"made":"twice"}', {}]) });
  const res = await apiClient()("/charged/thing", { method: "POST", body: "{}" });
  assert.equal(res.status, 500);
  assert.equal(posts().length, 1);
  assert.equal(signIns().length, 0);
});

test("an HTML page below 500 (the login page served as a 200) still signs in again and retries once", async () => {
  prepare({ "POST /charged/thing": seq([200, "<!DOCTYPE html><html><body>Sign in</body></html>", HTML], [200, '{"made":"once"}', {}]) });
  const res = await apiClient()("/charged/thing", { method: "POST", body: "{}" });
  assert.equal(res.status, 200);
  assert.deepEqual(await res.json(), { made: "once" });
  assert.equal(posts().length, 2);
  assert.equal(signIns().length, 1);
});

test("verdict(): an HTML 5xx is ok (handed back); HTML below 500, a 401 and a 307 to /login are expired", () => {
  const res = (status, headers = {}) => new Response(null, { status, headers });
  for (const status of [500, 502, 503, 504, 599]) assert.equal(verdict(res(status, HTML), null), "ok", String(status));
  assert.equal(verdict(res(200, HTML), null), "expired");
  assert.equal(verdict(res(404, HTML), null), "expired");
  assert.equal(verdict(res(499, HTML), null), "expired");
  assert.equal(verdict(res(401), null), "expired");
  assert.equal(verdict(res(307, { location: "/login" }), null), "expired");
  assert.equal(verdict(res(200, { "content-type": "application/json" }), null), "ok");
});
